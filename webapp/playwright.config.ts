// Сквозные сценарии: настоящий Chromium против собранного приложения.
//
// Зачем они рядом с 148 тестами в jsdom. jsdom не считает раскладку вообще
// (getBoundingClientRect всегда нули, ширины и переносы не существуют) и не
// умеет ничего, что построено на измерении элементов, — а на измерении
// контейнера построена карта (map/MapView.tsx берёт размер из
// clientWidth/clientHeight и молча остаётся нулевой). Всё, что проверяется
// здесь, в jsdom либо подделывается, либо не проверяется вовсе.
//
// Что нужно для запуска — см. README, раздел «Сквозные сценарии»: собранное
// приложение, запущенный локально app.py на 127.0.0.1:8080 и переменная
// DEV_INIT_DATA с подписью того пользователя, которого этот app.py пускает.
import { defineConfig, devices } from "@playwright/test"

const PREVIEW_PORT = 4173
const BASE_URL = `http://127.0.0.1:${PREVIEW_PORT}`

export default defineConfig({
  testDir: "./e2e",
  // Один рабочий процесс, а не «по ядру на брата». Все сценарии подписаны
  // ОДНИМ пользователем, а сервер разрешает ему один тяжёлый запрос
  // одновременно (api.py:one_at_a_time → guards.INFLIGHT) и отвечает на
  // второй 429 «Уже считаю». Параллельные воркеры дрались бы за этот слот и
  // мигали бы отказом, не имеющим отношения к проверяемому поведению.
  workers: 1,
  fullyParallel: false,
  // Повторов нет намеренно: сценарий, который проходит со второй попытки, —
  // это мигающий сценарий, и прятать его перезапуском значит договориться
  // никогда его не чинить.
  retries: 0,
  reporter: "list",
  // Потолок на сценарий с запасом на настоящий поход в open-meteo: холодный
  // кэш сервера (engine.CACHE_TTL_MIN) на первом прогоне считает прогноз с
  // нуля. Сами ожидания привязаны к появлению данных на экране, а не к
  // этому числу — оно только не даёт зависшему прогону идти вечно.
  timeout: 90_000,
  expect: { timeout: 30_000 },
  use: {
    baseURL: BASE_URL,
    // Столько же, сколько у expect, и по той же причине: и «дождаться
    // вердикта», и «нажать кнопку, которая появляется вместе с вердиктом» —
    // одно и то же ожидание данных, самое долгое законное в наборе (холодный
    // кэш open-meteo). Без этой строки у действий потолка нет вовсе, и они
    // упираются в потолок СЦЕНАРИЯ: два сценария висели по 90 секунд на
    // нажатии не появившейся кнопки. Замерено на погашенном бэкенде —
    // 4,2 минуты без этой строки против 2,2 минуты с ней, при том же
    // раскладе 4 красных / 4 зелёных.
    actionTimeout: 30_000,
    // Ширина макета (miniapp/prototype.html — рамка телефона 452 px). Узкие
    // экраны проверяются точечно, там, где это и есть предмет проверки
    // (e2e/layout.spec.ts).
    viewport: { width: 452, height: 900 },
    trace: "retain-on-failure",
  },
  projects: [{ name: "chromium", use: { ...devices["Desktop Chrome"], viewport: { width: 452, height: 900 } } }],
  webServer: {
    // Сборка входит в команду намеренно: `vite preview` отдаёт dist как есть,
    // и без пересборки сценарии проверяли бы приложение с прошлого прогона —
    // правка исходника молча не доезжала бы до браузера.
    command: `npm run build && npm run preview -- --port ${PREVIEW_PORT} --strictPort`,
    url: BASE_URL,
    // Никогда не переиспользовать уже слушающий порт. Обещание строкой выше
    // («правка не доедет до браузера незамеченной») держится ТОЛЬКО этим:
    // при reuseExistingServer команда со сборкой не запускается вовсе, а
    // отданный dist остаётся от прошлого прогона. Воспроизведено: открытый
    // рядом `npm run preview` + внесённая регрессия `.chip--dep { flex: none }`
    // давали «1 passed», хотя та же правка на свободном порту краснеет на
    // 51 px. Обычное `!process.env.CI` здесь означало бы «всегда»: CI в
    // проекте нет.
    //
    // Цена: при занятом 4173 прогон падает с «port is used». Это и нужно —
    // громкий отказ вместо тихого прогона по вчерашней сборке.
    reuseExistingServer: false,
    timeout: 180_000,
    stdout: "pipe",
  },
})
