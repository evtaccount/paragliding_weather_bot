// Палитра графиков — переведена вручную из charts.py (корень репозитория,
// константы TERRAIN/BAND/TEMP/WIND/GUST/GRADE_RGB) и сверена питоновским
// тестом tests/test_palette_sync.py: тот тест читает ЭТОТ файл регулярным
// выражением и требует побайтового совпадения hex-значений. Разошлись —
// PNG из бота и приборы мини-приложения раскрашивают один и тот же день
// по-разному, а пилот не может понять, какой картинке верить.
//
// Формат объявлений подобран под регэксп теста:
// `(?:export const\s+)?(\w+)\s*[:=]\s*"(#[0-9a-fA-F]{6})"` — поэтому у
// скалярных цветов `export const X = "#rrggbb"`, а ключи GRADE — простые
// идентификаторы без кавычек (`ideal: "#..."`), а не строковые литералы:
// с кавычками перед двоеточием регэксп не совпадёт, и тест зазеленеет,
// ничего не найдя (см. task-7-brief, шаг про проверку теста на красноту).
//
// Меняя число здесь, меняй и charts.py — иначе тест сверки покраснеет
// первым и укажет, что именно разъехалось.

export const TERRAIN = "#968e80" // charts.TERRAIN — заливка рельефа
export const BAND = "#6eaad2" // charts.BAND — рабочий коридор термички
export const TEMP = "#c25e12" // charts.TEMP — ряд температуры
export const WIND = "#2f6fe0" // charts.WIND — ряд ветра
export const GUST = "#0e8c7c" // charts.GUST — ряд порывов

// Цвет категории лётности — charts.GRADE_RGB. Пороги, при которых час или
// день попадают в категорию, здесь не хранятся: они живут только в
// criteria.py, сюда переносится исключительно цвет.
export const GRADE: Record<string, string> = {
  ideal: "#16613a",
  excellent: "#3f8f57",
  fair: "#c69a1e",
  marginal: "#c25e12",
  no_fly: "#c23a52",
  danger: "#8c1e34",
  no_data: "#9e9e94",
}

// Бросает исключение на неизвестной категории, а не отдаёт серый по
// умолчанию: молчаливый серый скрыл бы ровно то расхождение с charts.py,
// ради поимки которого написан tests/test_palette_sync.py.
export function colorOfCategory(category: string): string {
  const color = GRADE[category]
  if (color === undefined) {
    throw new Error(`Нет цвета для категории лётности "${category}"`)
  }
  return color
}

