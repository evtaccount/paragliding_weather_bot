// Правило «какой старт показывать, пока пилот не выбрал сам» — одно на всё
// приложение: первый старт из /api/sites (библиотека общая и приходит в том
// порядке, в котором её отдаёт store.load_sites).
//
// Живёт отдельным модулем, а не в App.tsx: этим правилом пользуются и
// оболочка (App.tsx), и выбиралка старта (sheets/SitePickerSheet.tsx) — она
// ставит отметку «текущий» и обязана считать её ровно так же, иначе
// отмеченный старт разойдётся с тем, чей прогноз реально считается. Импорт
// из App.tsx давал бы цикл App → шторка → App ради чистой функции над
// Site[], никак с оболочкой не связанной (ревью задачи 13, круг 2).
import type { Site } from "./api/types"

// null и когда список ещё грузится, и когда он пуст — эти два случая
// различает вызывающий код (у оболочки для них разная разметка: индикатор
// против «Нет стартов»), самой функции достаточно знать «есть ли имя».
export function defaultSiteName(sites: Site[] | undefined): string | null {
  return sites?.[0]?.name ?? null
}
