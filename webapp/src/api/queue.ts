// Очередь тяжёлых запросов.
//
// Сервер разрешает один тяжёлый запрос на пилота одновременно и отвечает 429
// на второй (api.py: зависимость one_at_a_time, guards.INFLIGHT — один слот
// на user_id). Это ограничение остаётся серверным — очередь на клиенте его
// не обходит, а просто не даёт приложению самому в него врезаться: если
// пилот успевает открыть прогноз и сразу дёрнуть ветровую сетку, оба запроса
// проходят через одну очередь и выполняются по одному, строго в порядке
// вызова, а не параллельно.
//
// Реализация — одна модульная очередь: `waiting` копит задачи, пришедшие
// пока предыдущая ещё выполняется, `busy` отмечает, что голова очереди
// занята. `advance()` — общий «финалли» на задачу: он вызывается и при
// успехе, и при отказе, поэтому отказ одной задачи не запирает очередь —
// следующая всё равно стартует. Вариант, где очередь продолжается только
// из ветки успеха, застрял бы навсегда после первой же сетевой ошибки.
//
// `task()` оборачивается в try/catch, а не только в `.then(_, onRejected)`:
// задача может бросить СИНХРОННО, не успев вернуть промис вовсе (например,
// исключение в коде, который собирает query-параметры, до первого await).
// `.then()` ловит только отказ уже созданного промиса — синхронный throw
// мимо него: пойманное ревью (см. queue.test.ts) — такой throw головой
// очереди навсегда оставлял `busy = true` (advance() не вызывался), а
// такой же throw не первой задачей ронял исключение сквозь `advance()`
// вызывающей задачи и вешал саму задачу и всё, что после неё в `waiting`,
// навсегда — resolve/reject для неё уже не вызывались.
type Job = () => void

let busy = false
const waiting: Job[] = []

function advance(): void {
  const next = waiting.shift()
  if (next) {
    next()
  } else {
    busy = false
  }
}

export function heavy<T>(task: () => Promise<T>): Promise<T> {
  return new Promise<T>((resolve, reject) => {
    const run = (): void => {
      let result: Promise<T>
      try {
        result = task()
      } catch (error) {
        reject(error)
        advance()
        return
      }
      result.then(
        (value) => { resolve(value); advance() },
        (error: unknown) => { reject(error); advance() },
      )
    }
    if (busy) {
      waiting.push(run)
    } else {
      busy = true
      run()
    }
  })
}
