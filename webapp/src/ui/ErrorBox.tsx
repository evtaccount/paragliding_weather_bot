// Показ ошибки API — текст для пилота (ApiError.userMessage из client.ts),
// короткое вибро и кнопка повтора, когда повторять есть смысл.
//
// Кнопка повтора отделяет «сервер НЕ СМОГ» от «сервер НЕ ПРИНЯЛ». Повтор
// осмыслен там, где тот же запрос может пройти сам собой: 429 (слот пилота
// сейчас занят), 5xx (open-meteo или сервер не ответили) и сетевой отказ.
// На отказе разбора (400, 409 и прочие 4xx) тот же запрос даст тот же ответ,
// и кнопка вредна: пилот жмёт «+» на маршрутной скорости 45 (потолок
// store.SPEED_MAX), число дёргается на 46 и возвращается к 45 (черновик
// снимается в onSettled), а «Повторить» отправляет ровно 46 — значение,
// которого на экране уже нет, и так столько раз, сколько он нажмёт
// (финальное ревью ветки, Minor 7). 401/403 — частный случай того же
// правила: подпись не прошла проверку или пилота нет в списке допущенных.
//
// Вибро — короткое уведомление об отказе (telegram.ts:haptic → Telegram
// HapticFeedback.notificationOccurred). Здесь оно одно на всё приложение:
// ErrorBox — единственное место, где показывается ЛЮБОЙ отказ сервера, и
// вибро в нём не приходится повторять на каждом экране. Вне Telegram обёртка
// молча ничего не делает (telegram.ts).
import { useEffect } from "react"
import { haptic } from "../telegram"

// Не `ApiError`, хотя типы вызывающих хуков обещают именно его: до ErrorBox
// доезжает и отказ, до ответа сервера не дошедший вовсе — пропала сеть, и
// fetch отклонился с TypeError, у которого нет ни status, ни userMessage
// (client.ts строит ApiError только по ответу). Тип, обещавший строку там, где
// приходит undefined, и оставлял рамку с пустым объяснением. ApiError под это
// описание подходит структурно, поэтому вызывающий код не меняется.
type ShownError = {
  status?: number
  userMessage?: string
}

// Пилот смотрит прогноз, теряет сеть, переключается на «Обзор» — и видит
// «Не получилось», сразу «Повторить», а между ними пусто: молчащая рамка
// читается как поломка приложения (финальное ревью ветки, круг 2, I4). Это
// единственный отказ, где повтор осмыслен, поэтому сказать, что повторять,
// нужно словами.
const NO_RESPONSE_RU = "Нет связи — проверьте интернет и повторите."

type ErrorBoxProps = {
  error: ShownError
  onRetry: () => void
}

// Повтор прячется у отказов разбора (4xx), а не разрешается по списку
// «хороших» кодов: до ErrorBox доезжает и отказ БЕЗ кода — сеть пропала, и
// fetch отклонился, не дойдя до ответа (client.ts строит ApiError только по
// ответу сервера). У такого отказа повтор — единственное осмысленное
// действие, и правило «прячем известные 4xx» оставляет его на месте, а
// правило «показываем известные 5xx» отняло бы.
//
// 429 — исключение среди 4xx: это не «сервер не принял», а «слот пилота
// сейчас занят» (api.py:one_at_a_time), и тот же запрос пройдёт, как только
// сервер досчитает предыдущий.
function canRetryStatus(status: number | undefined): boolean {
  if (status === undefined) return true
  if (status === 429) return true
  return !(status >= 400 && status < 500)
}

export function ErrorBox({ error, onRetry }: ErrorBoxProps) {
  const canRetry = canRetryStatus(error.status)
  // Зависимость — сам объект ошибки: новый отказ (новая мутация, новый
  // запрос) даёт новый ApiError, и вибро повторяется; лишние перерисовки
  // того же отказа — нет.
  useEffect(() => { haptic("error") }, [error])
  return (
    <div className="empty">
      <b>Не получилось</b>
      {/* `??`, а не `||`: пустой текст сервера — это его решение промолчать
          (см. 403 в client.ts), а отсутствующий значит, что отвечать было
          некому. */}
      {error.userMessage ?? NO_RESPONSE_RU}
      {canRetry && (
        <div>
          <button type="button" onClick={onRetry}>Повторить</button>
        </div>
      )}
    </div>
  )
}
