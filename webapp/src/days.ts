// Окно дней, на которое домен вообще считает прогноз: даты от сегодняшней и
// на всю его глубину (engine.RANGE_DAYS["2weeks"], копия в ./domain под
// сверкой tests/test_webapp_sync.py).
//
// Отдельный модуль, потому что читателей у окна двое и оба обязаны видеть
// ОДНО и то же: выбиралка дня (sheets/DayPickerSheet) рисует по нему список, а
// шевроны в шапке (App.tsx) по нему шагают и по нему же решают, показывать ли
// себя. Вторая копия «сегодня … +13» разошлась бы с выбиралкой молча — пилот
// дошагал бы шевроном до дня, которого в списке нет, или наоборот упёрся бы в
// границу раньше него.
//
// Не в ./domain (где лежит само число) — тамошний файл собирает КОПИИ значений
// домена под питоновскую сверку, а тут вычисление; и не в ./format — оно
// читает ./domain, и импорт в обе стороны замкнул бы модули друг на друга.
import { RANGE_DAYS_2WEEKS } from "./domain"
import { isoDate } from "./format"

// Функция, а не константа: «сегодня» меняется, пока приложение открыто, и
// посчитанный однажды список к утру описывал бы вчерашнее окно.
//
// Дата — по местному поясу устройства (isoDate), сдвиг — через setDate:
// переход через конец месяца и переводы часов он берёт на себя сам, в отличие
// от арифметики по миллисекундам.
export function forecastDays(): string[] {
  const today = new Date()
  return Array.from({ length: RANGE_DAYS_2WEEKS }, (_, offset) => {
    const day = new Date(today)
    day.setDate(today.getDate() + offset)
    return isoDate(day)
  })
}

// Соседний день внутри окна: `step` — +1 (вперёд) или −1 (назад). null значит
// «шагнуть некуда» — либо день стоит на краю окна, либо его в окне нет вовсе
// (приложение осталось открытым за полночь, и «сегодня» уже другое). Для
// шеврона оба случая значат одно: кнопку не рисуем.
//
// Шаг — по индексу в самом окне, а не арифметикой над датой: границы, конец
// месяца и переводы часов уже решены в forecastDays, и второй раз решать их
// значило бы завести место, где можно ошибиться иначе.
export function dayInWindow(date: string, step: 1 | -1): string | null {
  const days = forecastDays()
  const at = days.indexOf(date)
  if (at === -1) return null
  return days[at + step] ?? null
}
