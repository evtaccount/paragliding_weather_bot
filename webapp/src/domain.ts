// Значения домена, скопированные в TypeScript, — и место, где эти копии
// собраны в одном файле, а не рассыпаны по экранам.
//
// Копии здесь по той же причине, по которой существует charts/palette.ts:
// языки разные, а значение нужно обоим. Сервер эти величины наружу не отдаёт
// и отдавать не должен — они не зависят ни от пилота, ни от ответа
// open-meteo, и отдельное поле в каждом ответе было бы платой за константу.
// Поэтому вместо передачи по сети их сверяет тест со стороны питона:
// tests/test_webapp_sync.py читает ЭТОТ файл и сравнивает каждое значение с
// его источником (engine.py, criteria.py, route.py). Разошлись — краснеет
// питоновский прогон, а не пилот на склоне.
//
// Правило простое: значение, которое зависит от запроса (модель прогноза,
// лётность дня, описание погоды), приходит ответом сервера; значение,
// одинаковое для всех запросов, живёт здесь под сверкой.

